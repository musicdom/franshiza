const test = require("node:test");
const assert = require("node:assert/strict");
const sales = require("../lib/sales");
const flow = require("../lib/sales-flow");
let session;
let sent;
const sendMessage = async (_chat, text) => sent.push(text);
const welcomeKeyboard = [];
test("guided picker keeps state and returns a recommendation", async () => {
  session = null; sent = [];
  sales.getSession = async () => session;
  sales.saveSession = async (_id, value) => (session = { ...value, updated_at: new Date().toISOString() });
  sales.cancelReminders = async () => true;
  sales.queueReminder = async () => "test";
  sales.recordEvent = async value => value;
  const run = async text => flow.handleSalesMessage({ chatId: "test-chat", sender: { name: "Tester" }, text, normalizedText: text.toLowerCase().replace(/^[^\p{L}\p{N}]+/u, "").trim(), sendMessage, welcomeKeyboard });
  assert.equal((await run("🎯 Подобрать бота")).action, "recommendation_started");
  assert.equal((await run("Салоны и барбершопы")).action, "business_selected");
  assert.equal((await run("📅 Записывать клиентов")).action, "goal_selected");
  assert.equal((await run("⚡ Запуститься быстрее")).action, "recommendations");
  assert.equal(session.stage, "sales_recommendations");
  assert.ok(sent.at(-1).includes("Бот для салона красоты"));
});
